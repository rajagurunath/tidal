"""Online load generation for the A/B evaluation (plan B5).

The generator is split in two on purpose:

``schedule``
    A *pure*, seeded function from (shape, rate, duration) to a list of arrival
    offsets in seconds. Same seed → same schedule, byte for byte, so every
    condition in the A/B matrix sees the **identical** arrival process and the
    only thing that varies between runs is what the engine did with it.

``OnlineLoadGen``
    The async executor. It sleeps until each offset, fires one non-streaming
    chat completion straight at vLLM (never through the gateway — online
    traffic does not pass through Tidal), and records the wall-clock latency.

**On the latency metric.** We report *request latency*: the wall time from
issuing the HTTP POST to receiving the complete response. On this CPU dev box
non-streaming latency is TTFT + decode, so it is strictly larger than TTFT and
grows with ``max_tokens``. It is the honest thing to report for a non-streaming
client, and because every condition uses the same prompt set and the same
``max_tokens``, differences between conditions are still attributable to
co-serving interference. A TTFT-only number would need ``stream=True`` and a
streaming reader; that is left to the GPU runs where TTFT is the SLO that
matters.

Arrival shapes:

* ``poisson`` — homogeneous Poisson process at ``rps`` (exponential gaps).
* ``diurnal`` — non-homogeneous Poisson whose rate follows a sine over
  ``period_s``, generated by Lewis-Shedler thinning against the peak rate, so
  it is a genuine NHPP and not a rescaled homogeneous one. This is the shape
  the whole product thesis rests on: batch work is what fills the trough.
"""

from __future__ import annotations

import asyncio
import math
import random
import time
from collections.abc import Sequence
from dataclasses import asdict, dataclass, field

import httpx

__all__ = [
    "DEFAULT_PROMPTS",
    "OnlineLoadGen",
    "RequestRecord",
    "diurnal_schedule",
    "percentile",
    "poisson_schedule",
    "schedule",
    "summarize_latencies",
]

#: Short, cheap prompts — the point of the harness is scheduler behaviour, not
#: generation quality, and a CPU box cannot afford long prefills.
DEFAULT_PROMPTS: tuple[str, ...] = (
    "Name one fact about the ocean.",
    "Give a one-line definition of latency.",
    "What is a GPU used for? One sentence.",
    "Say hello in French.",
    "Name a prime number under 50.",
    "One short tip for writing tests.",
    "What does SLA stand for?",
    "Name one planet and one of its moons.",
)


def poisson_schedule(rps: float, duration_s: float, seed: int = 0) -> list[float]:
    """Arrival offsets of a homogeneous Poisson process on ``[0, duration_s)``.

    Args:
        rps: mean arrival rate (requests per second); must be > 0.
        duration_s: length of the window.
        seed: RNG seed — the whole point of this function.
    """
    if rps <= 0:
        raise ValueError("rps must be positive")
    if duration_s <= 0:
        return []
    rng = random.Random(seed)
    out: list[float] = []
    t = 0.0
    while True:
        t += rng.expovariate(rps)
        if t >= duration_s:
            return out
        out.append(t)


def diurnal_schedule(
    base_rps: float,
    peak_rps: float,
    duration_s: float,
    period_s: float,
    seed: int = 0,
    phase: float = 0.0,
) -> list[float]:
    """Arrival offsets of a sinusoidal non-homogeneous Poisson process.

    The instantaneous rate is
    ``λ(t) = base + (peak - base)·(1 + sin(2πt/period + phase))/2``, sampled by
    thinning a homogeneous process at ``peak_rps``. ``base_rps`` is the trough
    (the idle capacity a batch tier is supposed to monetize).
    """
    if peak_rps < base_rps:
        raise ValueError("peak_rps must be >= base_rps")
    if peak_rps <= 0:
        raise ValueError("peak_rps must be positive")
    if period_s <= 0:
        raise ValueError("period_s must be positive")
    if duration_s <= 0:
        return []
    rng = random.Random(seed)
    amplitude = peak_rps - base_rps
    out: list[float] = []
    t = 0.0
    while True:
        t += rng.expovariate(peak_rps)
        if t >= duration_s:
            return out
        rate = base_rps + amplitude * (1.0 + math.sin(2.0 * math.pi * t / period_s + phase)) / 2.0
        if rng.random() < rate / peak_rps:  # thinning
            out.append(t)


def schedule(
    shape: str,
    rps: float,
    duration_s: float,
    seed: int = 0,
    *,
    period_s: float = 600.0,
    trough_frac: float = 0.2,
) -> list[float]:
    """Dispatch to an arrival shape by name (``"poisson"`` | ``"diurnal"``).

    For ``diurnal``, ``rps`` is the *peak* rate and the trough is
    ``trough_frac · rps``.
    """
    if shape == "poisson":
        return poisson_schedule(rps, duration_s, seed)
    if shape == "diurnal":
        return diurnal_schedule(rps * trough_frac, rps, duration_s, period_s, seed)
    raise ValueError(f"unknown arrival shape {shape!r} (want 'poisson' or 'diurnal')")


@dataclass
class RequestRecord:
    """One online request's outcome. Times are seconds since run start."""

    index: int
    scheduled_at: float
    started_at: float
    finished_at: float
    latency_s: float
    status: int
    prompt_tokens: int = 0
    completion_tokens: int = 0
    error: str | None = None

    @property
    def ok(self) -> bool:
        return self.error is None and self.status == 200

    def as_dict(self) -> dict:
        return asdict(self)


def percentile(values: Sequence[float], q: float) -> float:
    """Linear-interpolation percentile, ``q`` in ``[0, 1]`` (numpy's default).

    Returns ``nan`` for an empty input rather than raising: a condition that
    produced no successful requests is a result, not a crash.
    """
    if not values:
        return float("nan")
    if not 0.0 <= q <= 1.0:
        raise ValueError("q must be in [0, 1]")
    ordered = sorted(values)
    if len(ordered) == 1:
        return float(ordered[0])
    pos = (len(ordered) - 1) * q
    low = math.floor(pos)
    high = math.ceil(pos)
    if low == high:
        return float(ordered[low])
    return float(ordered[low] + (ordered[high] - ordered[low]) * (pos - low))


def summarize_latencies(values: Sequence[float]) -> dict[str, float]:
    """Count, mean and the percentiles the paper reports."""
    if not values:
        return {
            "count": 0,
            "mean": float("nan"),
            "p50": float("nan"),
            "p90": float("nan"),
            "p95": float("nan"),
            "p99": float("nan"),
            "max": float("nan"),
        }
    return {
        "count": len(values),
        "mean": float(sum(values) / len(values)),
        "p50": percentile(values, 0.50),
        "p90": percentile(values, 0.90),
        "p95": percentile(values, 0.95),
        "p99": percentile(values, 0.99),
        "max": float(max(values)),
    }


@dataclass
class OnlineLoadGen:
    """Fires a pre-computed arrival schedule at a vLLM OpenAI server.

    Attributes:
        base_url: vLLM root, e.g. ``http://127.0.0.1:8397``.
        model: served model name.
        max_tokens: decode budget per online request.
        priority: online priority; 0 in every condition (Tidal's contract).
        prompts: prompt pool, cycled deterministically by request index.
        timeout_s: per-request HTTP timeout.
    """

    base_url: str
    model: str
    max_tokens: int = 16
    priority: int = 0
    prompts: Sequence[str] = DEFAULT_PROMPTS
    timeout_s: float = 300.0
    temperature: float = 0.0
    records: list[RequestRecord] = field(default_factory=list)

    # -- the run -----------------------------------------------------------

    async def run(
        self,
        offsets: Sequence[float],
        *,
        client: httpx.AsyncClient | None = None,
        t0: float | None = None,
    ) -> list[RequestRecord]:
        """Fire every offset, wait for all of them, return the records.

        Requests are launched as independent tasks: a slow response delays that
        request's record, never the arrival process. That is what makes the
        measurement an *open-loop* one — the load offered does not shrink when
        the system gets slower, which is the only way a queueing effect can
        show up in the numbers at all.
        """
        owns = client is None
        # A load generator must never self-throttle: the default httpx pool
        # caps at 100 connections, which silently converts this open-loop
        # generator into a closed loop exactly when the engine is saturated —
        # understating the latency damage it exists to measure.
        http = client or httpx.AsyncClient(
            timeout=self.timeout_s,
            limits=httpx.Limits(max_connections=None, max_keepalive_connections=100),
        )
        start = t0 if t0 is not None else time.perf_counter()
        tasks: list[asyncio.Task] = []
        try:
            for index, offset in enumerate(offsets):
                delay = start + offset - time.perf_counter()
                if delay > 0:
                    await asyncio.sleep(delay)
                tasks.append(
                    asyncio.create_task(
                        self._one(http, index, offset, start), name=f"online-{index}"
                    )
                )
            records = await asyncio.gather(*tasks)
        finally:
            if owns:
                await http.aclose()
        self.records = sorted(records, key=lambda r: r.index)
        return self.records

    async def _one(
        self, http: httpx.AsyncClient, index: int, offset: float, start: float
    ) -> RequestRecord:
        body = self.body_for(index)
        began = time.perf_counter()
        status = 0
        error: str | None = None
        ptoks = ctoks = 0
        try:
            response = await http.post(
                f"{self.base_url.rstrip('/')}/v1/chat/completions",
                json=body,
                timeout=self.timeout_s,
            )
            status = response.status_code
            if status == 200:
                usage = (response.json() or {}).get("usage") or {}
                ptoks = int(usage.get("prompt_tokens") or 0)
                ctoks = int(usage.get("completion_tokens") or 0)
            else:
                error = f"HTTP {status}: {response.text[:200]}"
        except Exception as exc:  # network, timeout, malformed JSON
            error = f"{type(exc).__name__}: {exc}"
        ended = time.perf_counter()
        return RequestRecord(
            index=index,
            scheduled_at=offset,
            started_at=began - start,
            finished_at=ended - start,
            latency_s=ended - began,
            status=status,
            prompt_tokens=ptoks,
            completion_tokens=ctoks,
            error=error,
        )

    def body_for(self, index: int) -> dict:
        """The chat body for request ``index`` — deterministic in the index."""
        prompt = self.prompts[index % len(self.prompts)]
        return {
            "model": self.model,
            "messages": [{"role": "user", "content": prompt}],
            "max_tokens": self.max_tokens,
            "temperature": self.temperature,
            "priority": self.priority,
            "stream": False,
        }

    # -- summaries ---------------------------------------------------------

    def latencies(self) -> list[float]:
        return [r.latency_s for r in self.records if r.ok]

    def summary(self) -> dict[str, float]:
        stats = summarize_latencies(self.latencies())
        stats["errors"] = float(sum(1 for r in self.records if not r.ok))
        return stats
